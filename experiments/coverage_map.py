"""Coverage map: where our simulated scenarios sit, and where real hardware sits.

Three panels:
  (a) parameter space sigma_q / L vs rho: E1-E8 sweep points, the range each
      E9-E11 schedule spans (5-95% of the values it generates), the LSTM training
      boxes, and the Sivak et al. 2023 operating point. rho has never been
      measured for GKP hardware, so the hardware point is a vertical band over
      all rho, with the measured T1 drift amplitude as its sigma_q spread.
  (b) parameter space sigma_q / L vs sigma_m / L, same sources.
  (c) syndrome-feature space (what a decoder sees): per-sequence syndrome
      spread vs lag-1 syndrome correlation for each scenario family, and the
      hardware-scale point simulated at several rho.

For each hardware anchor the script reports the distance to the nearest
simulated scenario in standardised feature units, as a coverage measure.

Run from the repo root:
    MPLBACKEND=Agg python -m experiments.coverage_map
Writes results/benchmarks/coverage_map.json and coverage_map.png.
"""

import json
import math

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt
import numpy as np

from experiments.common import BROAD_BOX, NOMINAL, get_mode, log, make_rng, out_dir
from experiments.run_all import E2_LEVELS, E2_RHOS, E3_SQ, E4_SM, SWITCHING
from experiments.run_nonstationary import POINTS
from simulator import nonstationary as ns
from simulator.fast import syndromes_and_nl
from simulator.noise import L, NoiseModel
from simulator.switching import SwitchingNoiseModel
from training.datasets import DRIFT_TRAIN_MIX

OUT = out_dir() / "benchmarks"
OUT.mkdir(parents=True, exist_ok=True)
QUICK = get_mode() == "quick"

# hardware anchors (docs/benchmarks.md, sections A and B)
SIVAK_SQ = 0.0720            # sigma_q / L from cavity loss (T1 = 610 us, cycle 9.85 us)
SIVAK_SM = (0.102, 0.109)    # sigma_m / L that reproduces p_X = 1.81e-3 (NL, Bayes)
SIVAK_SM_DELTA = 0.1356      # Delta / sqrt(2), Delta = 0.34
T1_REL_SIGMA = 0.088         # median relative sigma_q spread of the measured T1 drift


def stationary_points():
    """(label, sigma_q/L, rho, sigma_m/L) for E1-E6."""
    pts = [("E1 nominal", 0.20, 0.90, 0.05)]
    for lv, (sq, sm) in E2_LEVELS.items():
        pts += [(f"E2-{lv}", sq, r, sm) for r in E2_RHOS]
    pts += [("E3", s, 0.90, 0.05) for s in E3_SQ]
    pts += [("E4", 0.20, 0.90, s) for s in E4_SM]
    pts += [("E6 switching", 0.20, r, 0.05) for r in (SWITCHING["rho_lo"], SWITCHING["rho_hi"])]
    return pts


def schedule_ranges(n=300, T=1000):
    """5-95% range of sigma_q/L, rho and sigma_m/L generated by each E9-E11 point."""
    out = {}
    for exp, pts in POINTS.items():
        for k, (pid, spec, _) in enumerate(pts):
            sch = ns.make_schedule(spec, make_rng("dev", "coverage", k), n, T)
            q = lambda a: [float(np.percentile(a, 5)), float(np.percentile(a, 95))]
            out[f"{exp}/{pid}"] = dict(sigma_q=q(sch.sigma_q / L), rho=q(sch.rho),
                                       sigma_m=q(sch.sigma_m / L), family=spec["family"])
    return out


def features(d, n):
    s, _ = syndromes_and_nl(d, n)
    s = s / L
    sc = s - s.mean(axis=1, keepdims=True)
    var = (sc ** 2).mean(axis=1)
    lag1 = (sc[:, :-1] * sc[:, 1:]).mean(axis=1) / np.maximum(var, 1e-12)
    return np.sqrt(var), lag1


def feature_clouds():
    N = 300 if QUICK else 1500
    T = 200
    rng = lambda k: make_rng("dev", "coverage_feat", k)
    clouds = {}
    d, n = NoiseModel(**NOMINAL).sample(rng(0), N, T)
    clouds["E1 nominal"] = features(d, n)
    for i, rho in enumerate((0.0, 0.5, 0.95)):
        d, n = NoiseModel(0.2 * L, 0.05 * L, rho).sample(rng(1 + i), N, T)
        clouds[f"E2 rho={rho}"] = features(d, n)
    for i, sq in enumerate((0.10, 0.30)):
        d, n = NoiseModel(sq * L, 0.05 * L, 0.9).sample(rng(10 + i), N, T)
        clouds[f"E3 sigma_q={sq}L"] = features(d, n)
    d, n = NoiseModel(0.2 * L, 0.12 * L, 0.9).sample(rng(20), N, T)
    clouds["E4 sigma_m=0.12L"] = features(d, n)
    d, n = SwitchingNoiseModel().sample(rng(21), N, T)
    clouds["E6 switching"] = features(d, n)
    for k, (exp, pts) in enumerate(POINTS.items()):
        for j, (pid, spec, _) in enumerate(pts):
            d, n, _ = ns.sample(spec, rng(100 + 10 * k + j), N, T)
            clouds[f"{exp}/{pid}"] = features(d, n)
    d, n, _, _ = ns.sample_mixture(DRIFT_TRAIN_MIX, rng(200), N, T)
    clouds["LSTM-drift training mix"] = features(d, n)
    anchors = {}
    for i, rho in enumerate((0.0, 0.5, 0.9)):
        d, n = NoiseModel(SIVAK_SQ * L, np.mean(SIVAK_SM) * L, rho).sample(rng(300 + i), N, T)
        anchors[f"hardware scale, rho={rho}"] = features(d, n)
    return clouds, anchors


def nearest(anchors, clouds):
    """Distance from each anchor median to the nearest scenario median (standardised)."""
    meds = {k: np.array([np.median(v[0]), np.median(v[1])]) for k, v in clouds.items()}
    spread = np.array([np.std([m[0] for m in meds.values()]), np.std([m[1] for m in meds.values()])])
    out = {}
    for a, v in anchors.items():
        am = np.array([np.median(v[0]), np.median(v[1])])
        dist = {k: float(np.linalg.norm((am - m) / spread)) for k, m in meds.items()}
        best = min(dist, key=dist.get)
        out[a] = dict(median_syndrome_sd=float(am[0]), median_lag1=float(am[1]),
                      nearest_scenario=best, distance=dist[best])
    return out


def main():
    pts = stationary_points()
    ranges = schedule_ranges()
    clouds, anchors = feature_clouds()
    cover = nearest(anchors, clouds)

    fig, axes = plt.subplots(1, 3, figsize=(17, 5.2))
    ax = axes[0]
    for lbl, sq, rho, sm in pts:
        ax.scatter(sq, rho, s=22, color="C0", zorder=3)
    ax.add_patch(plt.Rectangle((BROAD_BOX["sigma_q"][0] / L, BROAD_BOX["rho"][0]),
                               (BROAD_BOX["sigma_q"][1] - BROAD_BOX["sigma_q"][0]) / L,
                               BROAD_BOX["rho"][1] - BROAD_BOX["rho"][0], fill=False,
                               ec="C1", lw=1.5, label="LSTM-broad training box"))
    for k, r in ranges.items():
        ax.plot(r["sigma_q"], [np.mean(r["rho"])] * 2, color="C2", lw=2, alpha=0.7)
        ax.plot([np.mean(r["sigma_q"])] * 2, r["rho"], color="C2", lw=2, alpha=0.7)
    ax.axvspan(SIVAK_SQ * (1 - T1_REL_SIGMA), SIVAK_SQ * (1 + T1_REL_SIGMA), color="C3",
               alpha=0.25, label="hardware sigma_q (Sivak), rho unmeasured")
    ax.scatter([], [], color="C0", label="E1-E8 stationary points")
    ax.plot([], [], color="C2", label="E9-E11 schedule ranges (5-95%)")
    ax.set_xlabel("sigma_q / L")
    ax.set_ylabel("rho")
    ax.set_title("(a) parameter space: noise strength vs correlation")
    ax.legend(fontsize=7, loc="lower right")
    ax.grid(alpha=0.3)

    ax = axes[1]
    for lbl, sq, rho, sm in pts:
        ax.scatter(sq, sm, s=22, color="C0", zorder=3)
    ax.add_patch(plt.Rectangle((BROAD_BOX["sigma_q"][0] / L, BROAD_BOX["sigma_m"][0] / L),
                               (BROAD_BOX["sigma_q"][1] - BROAD_BOX["sigma_q"][0]) / L,
                               (BROAD_BOX["sigma_m"][1] - BROAD_BOX["sigma_m"][0]) / L,
                               fill=False, ec="C1", lw=1.5))
    for k, r in ranges.items():
        ax.plot(r["sigma_q"], [np.mean(r["sigma_m"])] * 2, color="C2", lw=2, alpha=0.7)
    ax.errorbar([SIVAK_SQ], [np.mean(SIVAK_SM)], xerr=[[SIVAK_SQ * T1_REL_SIGMA]],
                yerr=[[np.mean(SIVAK_SM) - SIVAK_SM[0]]], fmt="*", ms=14, color="C3",
                label="hardware (Sivak; sigma_m calibrated)")
    ax.scatter([SIVAK_SQ], [SIVAK_SM_DELTA], marker="x", s=60, color="C3",
               label="sigma_m = Delta/sqrt(2)")
    ax.set_xlabel("sigma_q / L")
    ax.set_ylabel("sigma_m / L")
    ax.set_title("(b) parameter space: noise strength vs readout noise")
    ax.legend(fontsize=7, loc="upper right")
    ax.grid(alpha=0.3)

    ax = axes[2]
    cmap = plt.cm.tab20(np.linspace(0, 1, len(clouds)))
    for (k, (sd, lag)), c in zip(clouds.items(), cmap):
        ax.scatter(np.median(sd), np.median(lag), color=c, s=30, zorder=3)
        ax.plot([np.percentile(sd, 25), np.percentile(sd, 75)], [np.median(lag)] * 2, color=c, lw=1)
        ax.plot([np.median(sd)] * 2, [np.percentile(lag, 25), np.percentile(lag, 75)], color=c, lw=1)
    for k, (sd, lag) in anchors.items():
        ax.scatter(np.median(sd), np.median(lag), marker="*", s=180, color="C3", zorder=4)
        ax.annotate(k.replace("hardware scale, ", "hw "), (np.median(sd), np.median(lag)),
                    fontsize=7, xytext=(5, 4), textcoords="offset points")
    ax.set_xlabel("per-sequence syndrome SD / L")
    ax.set_ylabel("lag-1 syndrome correlation")
    ax.set_title("(c) what decoders see (median, IQR); stars: hardware scale")
    ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(OUT / "coverage_map.png", dpi=150)
    plt.close(fig)

    out = dict(
        stationary_points=[dict(label=l, sigma_q=s, rho=r, sigma_m=m) for l, s, r, m in pts],
        schedule_ranges=ranges,
        feature_medians={k: [float(np.median(v[0])), float(np.median(v[1]))] for k, v in clouds.items()},
        hardware_anchor_coverage=cover,
        parameter_gaps=dict(
            min_sigma_q_simulated=float(min(p[1] for p in pts)),
            sigma_q_hardware=SIVAK_SQ,
            nonstationary_min_sigma_q=float(min(r["sigma_q"][0] for r in ranges.values())),
            sigma_m_drift_points=sum(1 for r in ranges.values() if r["sigma_m"][1] - r["sigma_m"][0] > 1e-9),
            rho_measured_for_hardware=False,
        ),
    )
    (OUT / "coverage_map.json").write_text(json.dumps(out, indent=1))
    for a, c in cover.items():
        log(f"coverage: {a}: nearest {c['nearest_scenario']} at distance {c['distance']:.2f} "
            f"(syndrome SD {c['median_syndrome_sd']:.3f}, lag-1 {c['median_lag1']:.3f})")
    log(f"coverage_map: wrote {OUT}")


if __name__ == "__main__":
    main()
